const QUICK_ACTIONS: { kind: QuickKind; label: string; icon: typeof Plus }[] = [
  { kind: 'task', label: 'Task', icon: ListChecks },
  { kind: 'project', label: 'Project', icon: Folder },
  { kind: 'note', label: 'Note', icon: Notebook },
  { kind: 'contact', label: 'Contact', icon: UserPlus },
  { kind: 'reminder', label: 'Reminder', icon: CalendarClock },
  { kind: 'import', label: 'Import', icon: Import },
]

/** Modules that are not built yet, shown disabled exactly as the brief asks. */
const FUTURE_ACTIONS: { label: string; anchor: string; phase: 2; icon: typeof Plus }[] = [
  { label: 'New lead', anchor: 'crm', phase: 2, icon: Users },
  { label: 'New job application', anchor: 'career', phase: 2, icon: Target },
]

export default function DashboardView() {
  const dash = useResource<Dashboard>('/dashboard')
  const slug = useWorkspaceSlug()
  const quick = useQuickCreate()
  const [stored, setStored] = useLocalState<WidgetPrefs>(widgetPrefsKey(slug), defaultWidgetPrefs())
  const prefs = useMemo(() => normaliseWidgetPrefs(stored), [stored])
  const [customising, setCustomising] = useState(false)
  const [dragId, setDragId] = useState<WidgetId | null>(null)
  const refreshRequested = useRef(false)

  // API.md: derived notifications are generated by POST /notifications/refresh,
  // which the dashboard calls once per mount — GETs never create them.
  useEffect(() => {
    if (refreshRequested.current) return
    refreshRequested.current = true
    api<{ created: number; resolved: number }>('/notifications/refresh', { method: 'POST' })
      .then((res) => {
        if (res && (res.created > 0 || res.resolved > 0)) {
          invalidate('/notifications', '/dashboard')
          if (res.created > 0) toastSuccess(`${res.created} new notification${res.created === 1 ? '' : 's'}`)
        }
      })
      .catch(() => {
        /* an unreachable backend already shows in the error state */
      })
  }, [])

  const today = dash.data?.today ?? todayDate()
  const openTasks = dash.data?.tasks.open ?? 0
  const overdueTasks = dash.data?.tasks.overdue?.length ?? 0
  const dueTodayTasks = dash.data?.tasks.due_today?.length ?? 0
  const doneThisWeek = dash.data?.tasks.completed_this_week ?? 0
  /** Share of this week's workload that is already finished — real numbers only. */
  const weekCompletion =
    doneThisWeek + openTasks > 0
      ? Math.round((doneThisWeek / (doneThisWeek + openTasks)) * 100)
      : 0

  function hide(id: WidgetId) {
    setStored((prev) => ({ ...normaliseWidgetPrefs(prev), hidden: [...normaliseWidgetPrefs(prev).hidden, id] }))
  }

  function show(id: WidgetId) {
    setStored((prev) => ({
      ...normaliseWidgetPrefs(prev),
      hidden: normaliseWidgetPrefs(prev).hidden.filter((item) => item !== id),
    }))
  }

  function move(id: WidgetId, direction: -1 | 1) {
    setStored((prev) => {
      const base = normaliseWidgetPrefs(prev)
      return { ...base, order: moveWidget(base.order, id, direction) }
    })
  }

  function reorder(target: WidgetId) {
    if (!dragId || dragId === target) return
    const source = dragId
    setStored((prev) => {
      const base = normaliseWidgetPrefs(prev)
      const order = [...base.order]
      const from = order.indexOf(source)
      const to = order.indexOf(target)
      if (from === -1 || to === -1) return base
      order.splice(to, 0, ...order.splice(from, 1))
      return { ...base, order }
    })
    setDragId(null)
  }

  const visible = prefs.order.filter((id) => !prefs.hidden.includes(id))
  const hidden = prefs.order.filter((id) => prefs.hidden.includes(id))

  return (
    <div className="mx-auto w-full max-w-[112rem] space-y-6">
      {/* The one earned statement block: a bounded grid field, real numbers, one dial. */}
      <section className="os-enter">
        <GridField height={208} className="min-w-0">
          <div className="flex h-full flex-wrap items-end justify-between gap-6 px-1">
            <div className="min-w-0">
              <p className="os-label">{greeting()} · {formatDate(today, 'cccc d MMMM')}</p>
              <p className="os-display mt-3 max-w-3xl">
                {dash.data
                  ? summaryHeadline(dash.data)
                  : dash.loading
                    ? 'Reading your workspace…'
                    : 'MyOS overview'}
              </p>
              <MicroData
                className="mt-4"
                items={[
                  `${openTasks} open`,
                  `${overdueTasks} overdue`,
                  `${dueTodayTasks} due today`,
                  dash.data ? formatDateTime(new Date().toISOString()) : null,
                ]}
              />
            </div>
            <Dial value={weekCompletion} size={96} label="week" />
          </div>
        </GridField>
      </section>

      {/* Figures, not tiles: display numbers over hairline labels, divided by lines. */}
      <section aria-label="Workspace figures" className="grid grid-cols-2 border-y border-line sm:grid-cols-3 lg:grid-cols-6">
        <Figure value={openTasks} label="open tasks" />
        <Figure value={overdueTasks} label="overdue" tone={overdueTasks ? 'text-destructive' : undefined} />
        <Figure value={dueTodayTasks} label="due today" tone={dueTodayTasks ? 'text-warning' : undefined} />
        <Figure value={doneThisWeek} label="done this week" tone={doneThisWeek ? 'text-success' : undefined} />
        <Figure value={dash.data?.projects.active.length ?? 0} label="active projects" />
        <Figure value={dash.data?.notifications.unread ?? 0} label="unread alerts" />
      </section>

      <section className="min-w-0">
        <p className="os-label mb-3 border-b border-line pb-2">Quick actions</p>
        <div className="flex flex-wrap items-center gap-2">
          {QUICK_ACTIONS.map((action) => {
            const Icon = action.icon
            return (
              <Button
                key={action.kind}
                size="sm"
                variant="outline"
                onClick={() => quick.open(action.kind)}
              >
                <Icon />
                {action.label}
              </Button>
            )
          })}
          {FUTURE_ACTIONS.map((action) => {
            const Icon = action.icon
            return (
              <Hint key={action.label} label={`Phase ${action.phase} — not built yet`}>
                <Link
                  href={roadmapHref(action.anchor)}
                  className="inline-flex h-7 items-center gap-1.5 whitespace-nowrap rounded-os border border-dashed border-line px-2.5 text-xs text-faint transition-colors hover:border-line-strong hover:text-muted-foreground focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
                  aria-disabled="true"
                >
                  <Icon className="size-4" />
                  {action.label}
                  <Badge tone="outline" size="sm">
                    Phase {action.phase}
                  </Badge>
                </Link>
              </Hint>
            )
          })}
        </div>

        <div className="mt-3 flex flex-wrap items-center gap-2 border-t border-line pt-3">
          <Button
            size="sm"
            variant={customising ? 'default' : 'ghost'}
            onClick={() => setCustomising((prev) => !prev)}
            aria-pressed={customising}
          >
            <Settings2 />
            {customising ? 'Done customising' : 'Customise'}
          </Button>
          {customising ? (
            <>
              <span className="text-[11px] text-faint">
                Drag cards, or use the arrows. Hide/show and order are saved for this workspace only.
              </span>
              <Button
                size="sm"
                variant="ghost"
                onClick={() => setStored(defaultWidgetPrefs())}
              >
                <RotateCw /> Reset layout
              </Button>
            </>
          ) : (
            <span className="text-[11px] text-faint">
              {visible.length} of {WIDGET_DEFS.length} widgets shown
            </span>
          )}
        </div>

        {customising && hidden.length ? (
          <div className="mt-3 flex flex-wrap items-center gap-2 rounded-os border border-dashed border-line px-3 py-2">
            <span className="os-label">Hidden</span>
            {hidden.map((id) => {
              const def = WIDGET_DEFS.find((widget) => widget.id === id)
              if (!def) return null
              return (
                <button
                  key={id}
                  type="button"
                  onClick={() => show(id)}
                  className="os-tap-none inline-flex h-7 items-center gap-1.5 rounded-os border border-line px-2.5 text-xs text-muted-foreground transition-colors hover:bg-accent hover:text-foreground"
                >
                  <Eye className="size-3.5" />
                  {def.title}
                </button>
              )
            })}
          </div>
        ) : null}
      </section>

      <ResourceState
        resource={dash}
        skeleton={<LoadingCards count={6} />}
        empty={
          <p className="border-y border-dashed border-line px-4 py-8 text-center text-xs text-muted-foreground">
            The API answered but returned no dashboard payload. Reload to try again.
          </p>
        }
      >
        {(data) => (
          <div className="grid min-w-0 gap-3 md:grid-cols-2 xl:grid-cols-3">
            {visible.map((id) => (
              <WidgetFrame
                key={id}
                id={id}
                customising={customising}
                order={prefs.order.filter((item) => !prefs.hidden.includes(item))}
                onMove={move}
                onHide={hide}
                onDragStart={setDragId}
                onDrop={reorder}
                dragActive={!!dragId}
              >
                {renderWidget(id, data, quick.open)}
              </WidgetFrame>
            ))}
          </div>
        )}
      </ResourceState>
    </div>
  )
}

/* ------------------------------------------------------------------ widgets */

function renderWidget(
  id: WidgetId,
  data: Dashboard,
  open: ReturnType<typeof useQuickCreate>['open']
): ReactNode {
  switch (id) {
    case 'insights':
      return <InsightsWidget insights={data.insights} />
    case 'money':
      return <MoneyWidget today={data.today} />
    case 'agenda':
      return <AgendaWidget data={data} />
    case 'today':
      return (
        <TaskList
          tasks={data.tasks.due_today}
          showProject
          onEdit={(task) => open('task', { title: task.title })}
          emptyLabel="Nothing due today. Enjoy it."
        />
      )
    case 'overdue':
      return (
        <TaskList
          tasks={data.tasks.overdue}
          showProject
          onEdit={(task) => open('task', { title: task.title })}
          emptyLabel="Nothing overdue."
        />
      )
    case 'projects':
      return <ActiveProjects projects={data.projects.active} soon={data.projects.deadline_soon} />
    case 'milestones':
      return <MilestonesWidget milestones={data.milestones.upcoming} />
    case 'notifications':
      return <NotificationsWidget items={data.notifications.items} unread={data.notifications.unread} />
    case 'notes':
      return <NotesWidget notes={data.notes.recent} />
    case 'activity':
      return <ActivityRows items={data.activity.slice(0, 12)} />
    default:
      return null
  }
}

function InsightsWidget({ insights }: { insights: Dashboard['insights'] }) {
  if (!insights?.length) {
    return (
      <p className="text-xs text-muted-foreground">
        No patterns to flag. Insights are rule-based in Phase 1: overdue clusters, stalled projects,
        targets past due, unlinked notes and milestones within a week.
      </p>
    )
  }
  return (
    <ul className="min-w-0 space-y-1.5">
      {insights.map((insight, index) => (
        <li
          key={`${insight.kind}-${index}`}
          className="flex min-w-0 items-start gap-2 rounded-os px-2.5 py-2"
        >
          <StatusDot state="open" tone={insight.severity === "critical" ? "critical" : insight.severity === "warning" ? "warning" : undefined} className="mt-1.5" title={insight.severity} />
          {insight.href ? (
            <Link
              href={osHref(insight.href)}
              className="min-w-0 flex-1 text-[12.5px] leading-snug underline-offset-2 hover:text-primary hover:underline focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
            >
              {insight.text}
            </Link>
          ) : (
            <span className="min-w-0 flex-1 text-[12.5px] leading-snug">{insight.text}</span>
          )}
          <span className="os-label">{insight.kind.replace(/_/g, ' ')}</span>
        </li>
      ))}
    </ul>
  )
}

function AgendaWidget({ data }: { data: Dashboard }) {
  const reminders = data.reminders?.due ?? []
  const milestoneToday = (data.milestones?.upcoming ?? []).filter(
    (milestone) => milestone.date && milestone.date.slice(0, 10) === data.today
  )
  const tasks: Task[] = data.tasks.due_today ?? []

  if (!tasks.length && !reminders.length && !milestoneToday.length) {
    return (
      <p className="text-xs text-muted-foreground">
        Nothing on the calendar for {formatDate(data.today, 'd MMM')}.
      </p>
    )
  }

  return (
    <div className="min-w-0 space-y-2.5">
      {tasks.length ? (
        <Group label={`${tasks.length} task${tasks.length === 1 ? '' : 's'} due`}>
          <TaskList tasks={tasks} showProject={false} />
        </Group>
      ) : null}
      {reminders.length ? (
        <Group label="Reminders">
          <ul className="min-w-0 space-y-1">
            {reminders.slice(0, 6).map((reminder: Reminder) => (
              <li key={reminder.id} className="flex items-baseline gap-2 px-2 text-[12.5px]">
                <span className="os-num shrink-0 text-muted-foreground">
                  {formatDateTime(reminder.due_at).slice(-5)}
                </span>
                <span className="min-w-0 flex-1 truncate">{reminder.title}</span>
                <span className="shrink-0 text-[11px] text-faint">
                  {relativeFuture(reminder.due_at)}
                </span>
              </li>
            ))}
          </ul>
        </Group>
      ) : null}
      {milestoneToday.length ? (
        <Group label="Milestones today">
          <ul className="min-w-0 space-y-1">
            {milestoneToday.map((milestone: Milestone) => (
              <li key={milestone.id} className="px-2 text-[12.5px]">
                <Link
                  href={`/projects/${milestone.project_id}`}
                  className="underline-offset-2 hover:text-primary hover:underline"
                >
                  {milestone.title}
                </Link>
              </li>
            ))}
          </ul>
        </Group>
      ) : null}
    </div>
  )
}

function Group({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="min-w-0">
      <p className="os-label mb-1 px-2">{label}</p>
      {children}
    </div>
  )
}

function ActiveProjects({
  projects,
  soon,
}: {
  projects: Dashboard['projects']['active']
  soon: Dashboard['projects']['deadline_soon']
}) {
  if (!projects.length) {
    return (
      <div className="space-y-2">
        <p className="text-xs text-muted-foreground">No active projects yet.</p>
        <Link
          href="/projects"
          className="text-xs text-primary underline-offset-2 hover:underline"
        >
          Create the first one
        </Link>
      </div>
    )
  }
  return (
    <div className="min-w-0 space-y-3">
      <div className="grid min-w-0 gap-3 lg:grid-cols-2">
        {projects.slice(0, 6).map((project) => (
          <ProjectCard key={project.id} project={project} />
        ))}
      </div>
      {soon.length ? (
        <div className="rounded-os border border-warning/30 bg-warning/5 px-3 py-2">
          <p className="os-label mb-1 text-warning">Deadlines within 14 days</p>
          <ul className="flex flex-wrap gap-x-3 gap-y-1">
            {soon.map((item) => (
              <li key={item.id} className="text-[12px]">
                <Link
                  href={`/projects/${item.id}`}
                  className="underline-offset-2 hover:text-primary hover:underline"
                >
                  {item.name}
                </Link>
                <span className="os-num ml-1.5 text-warning">
                  {item.days_left < 0 ? `${Math.abs(item.days_left)}d late` : `${item.days_left}d`}
                </span>
              </li>
            ))}
          </ul>
        </div>
      ) : null}
    </div>
  )
}

function MilestonesWidget({ milestones }: { milestones: Milestone[] }) {
  if (!milestones.length) {
    return (
      <p className="text-xs text-muted-foreground">
        No milestones in the next 30 days. Add them on a project page.
      </p>
    )
  }
  return (
    <ul className="min-w-0 space-y-1">
      {milestones.slice(0, 8).map((milestone) => (
        <li key={milestone.id}>
          <Link
            href={`/projects/${milestone.project_id}`}
            className="flex min-w-0 items-baseline gap-2 rounded-os px-2 py-1.5 text-[12.5px] transition-colors hover:bg-canvas-deep"
          >
            <span
              className={cn(
                'os-num w-14 shrink-0 text-right',
                milestone.days_away == null
                  ? 'text-faint'
                  : milestone.days_away < 0
                    ? 'text-destructive'
                    : milestone.days_away <= 7
                      ? 'text-warning'
                      : 'text-muted-foreground'
              )}
            >
              {milestone.days_away == null
                ? '—'
                : milestone.days_away < 0
                  ? `${milestone.days_away}d`
                  : `${milestone.days_away}d`}
            </span>
            <span className="min-w-0 flex-1 truncate">{milestone.title}</span>
            <span className="shrink-0 text-[11px] text-faint">{formatDate(milestone.date, 'd MMM')}</span>
          </Link>
        </li>
      ))}
    </ul>
  )
}

